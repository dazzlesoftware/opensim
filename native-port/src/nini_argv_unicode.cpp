template <std::size_t N> bool contains(const std::pair<char16_t, char16_t> (&ranges)[N], char16_t c) {
    std::size_t a = 0, b = N;
    while (a < b) {
        auto m = (a + b) / 2;
        if (c < ranges[m].first)
            b = m;
        else if (c > ranges[m].second)
            a = m + 1;
        else
            return true;
    }
    return false;
}
