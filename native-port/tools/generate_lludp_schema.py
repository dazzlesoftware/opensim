"""Generate native packet layouts from the preserved template and DLL catalog.

The generated codec has no runtime .NET dependency. Regeneration is explicit;
normal native builds compile the checked-in table.
"""
import argparse
import json
from pathlib import Path
import re


def parse_template(text):
    tokens = re.findall(r"[{}]|[^\s{}]+", re.sub(r"//[^\n]*", "", text))
    position = 0
    messages = {}

    def take():
        nonlocal position
        value = tokens[position]
        position += 1
        return value

    def expect(value):
        actual = take()
        if actual != value:
            raise ValueError(f"Expected {value}, got {actual}")

    expect("version")
    take()
    while position < len(tokens):
        expect("{")
        name, frequency, number, trust, coding = [take() for _ in range(5)]
        while tokens[position] not in ("{", "}"):
            take()  # UDPDeprecated/UDPBlackListed flags.
        blocks = []
        while tokens[position] == "{":
            expect("{")
            block_name, mode = take(), take()
            count = int(take()) if mode == "Multiple" else (0 if mode == "Variable" else 1)
            fields = []
            while tokens[position] == "{":
                expect("{")
                field, field_type = take(), take()
                size = int(take()) if field_type in ("Fixed", "Variable") else 0
                expect("}")
                fields.append({"name": field, "type": field_type, "size": size})
            expect("}")
            blocks.append({"name": block_name, "mode": mode, "count": count, "fields": fields})
        expect("}")
        messages[name] = {"name": name, "frequency": "Low" if frequency == "Fixed" else frequency,
                          "id": int(number, 0) & 0xffff, "blocks": blocks}
    return messages


def generate(directory):
    messages = parse_template((directory / "message_template.msg").read_text())
    catalog = json.loads((directory / "packet-catalog.json").read_text())
    renames = json.loads((directory / "block-renames.json").read_text())
    types = {"U8": "Byte", "S8": "SByte", "U16": "UInt16", "S16": "Int16", "U32": "UInt32",
             "S32": "Int32", "U64": "UInt64", "S64": "Int64", "F32": "Single", "F64": "Double",
             "BOOL": "Boolean", "LLUUID": "UUID", "LLVector3": "Vector3", "LLVector3d": "Vector3d",
             "LLVector4": "Vector4", "LLQuaternion": "Quaternion", "IPADDR": "UInt32", "IPPORT": "UInt16",
             "Fixed": "Byte[]", "Variable": "Byte[]"}
    lines = ["// Generated by tools/generate_lludp_schema.py. Do not edit by hand.",
             "// Source and dependency provenance: protocol/provenance.json.",
             "// Protocol license and copyright: protocol/LIBOPENMETAVERSE-LICENSE.txt.",
             "static const std::vector<PacketSpec> schemas = {"]
    for packet in catalog:
        message = messages[packet["name"]]
        for block in message["blocks"]:
            block["name"] = renames.get(packet["name"], {}).get(block["name"], block["name"])
        if message["id"] != packet["id"] or message["frequency"] != packet["frequency"]:
            raise ValueError(f"Template ID differs from the tracked assembly: {packet['name']}")
        if [block["name"] for block in message["blocks"]] != [block["name"] for block in packet["blocks"]]:
            raise ValueError(f"Template block order differs: {packet['name']}")
        blocks = []
        for block, reflected in zip(message["blocks"], packet["blocks"]):
            expected = [(field["name"], types[field["type"]]) for field in block["fields"]]
            actual = [(field["name"], field["type"]) for field in reflected["fields"]]
            if expected != actual:
                raise ValueError(f"Template fields differ: {packet['name']}.{block['name']}: {expected} != {actual}")
            if reflected["type"].endswith("[]") != (block["mode"] != "Single"):
                raise ValueError(f"Template block multiplicity differs: {packet['name']}.{block['name']}")
            fields = ",".join('{"%s",FieldType::%s,%s}' % (field["name"], field["type"], field["size"]) for field in block["fields"])
            blocks.append('{"%s",%d,%s,{%s}}' % (block["name"], block["count"], str(block["mode"] == "Variable").lower(), fields))
        lines.append('{"%s",%d,Frequency::%s,%d,%s,%s,%s,{%s}},' %
                     (packet["name"], packet["enumValue"], packet["frequency"], packet["id"],
                      str(packet["reliable"]).lower(), str(packet["zerocoded"]).lower(),
                      str(packet["validateIds"]).lower(), ",".join(blocks)))
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--protocol", type=Path, default=Path(__file__).resolve().parents[1] / "protocol")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/lludp_schema.inc")
    parser.add_argument("--check", action="store_true", help="Verify the saved schema without modifying it")
    args = parser.parse_args()
    generated = generate(args.protocol)
    if args.check:
        if args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit("Saved LLUDP schema differs from the validated protocol catalog")
        print("Saved LLUDP schema matches the validated protocol catalog")
    else:
        args.output.write_text(generated, encoding="utf-8")
        print(f"Generated {args.output}")
